#Python Basic Data Operations On Pandas
 
import pandas as pd

#File name or File path
df=pd.read_csv("Empdata(CSV).csv")
print(df)
print("--------------------------------------------------------------------------------------")

#No. of rows and column
print(df.shape)
print("--------------------------------------------------------------------------------------")

#Disply First 5 Rows
print(df.head())
print("--------------------------------------------------------------------------------------")

#Disply Last 5 Rows
print(df.tail())
print("--------------------------------------------------------------------------------------")

#Disply First 2 Rows
print(df.head(2))
print("--------------------------------------------------------------------------------------")

#Disply Last 2 Rows
print(df.tail(2))
print("--------------------------------------------------------------------------------------")

#Retrive a Range of Rows
print(df[2:5])
print("--------------------------------------------------------------------------------------")

#Retrive Alternative Rows from df
print(df[0::2])
print("--------------------------------------------------------------------------------------")

#Retrive a Reverse Range of Rows
print(df[7:0:-1])
print("--------------------------------------------------------------------------------------")

#Retrive a column name
print(df.columns)
print("--------------------------------------------------------------------------------------")

#Retrive a particular column Data
print(df.Emp_Name)
print("--------------------------------------------------------------------------------------")












